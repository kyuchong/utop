/**
 * 선택지에 붙일 그림 — 글자 대신 눈으로 읽게(지시: 수동=손가락, 자동=톱니바퀴).
 *
 * 갈래마다 넉넉히 담고, 이름으로 찾을 수 있게 낱말을 붙였다(지적: 너무
 * 제한적이다). 이모지를 쓰는 까닭은 팔레트를 새로 만들 필요가 없고,
 * 저장도 글자 한 자면 되기 때문이다.
 */
export interface IconGroup {
  group: string
  items: Array<{ e: string; k: string }>
}
const g = (group: string, pairs: string): IconGroup => ({
  group,
  items: pairs
    .trim()
    .split(/\s+/)
    .map((p) => {
      const [e, k] = p.split('|')
      return { e: e ?? '', k: k ?? '' }
    }),
})

